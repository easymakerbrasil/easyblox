const createPictoBloxMappingCatalog =
    () => {
        const catalog =
            createCompatibilityCatalog(
                RAW_MAPPING_ENTRIES
            );

        const entries =
            Array.from(
                catalog.values()
            ).sort(
                (
                    left,
                    right
                ) =>
                    left.opcode
                        .localeCompare(
                            right.opcode
                        )
            );

        return {
            entries,
            totalMappingCount:
                entries.length
        };
    };

module.exports = {
    createPictoBloxMappingCatalog
};
