const fs = require('fs');
const path = require('path');

const sourceDirectory =
    path.resolve(
        __dirname,
        '../src/upload/arduino-runtime'
    );

const outputDirectory =
    path.resolve(
        __dirname,
        '../src/upload/generated'
    );

const outputPath =
    path.join(
        outputDirectory,
        'easyblox-arduino-runtime-files.js'
    );

const runtimeFileNames = [
    'EasyBlox.h',
    'EasyBloxBluetooth.h',
    'EasyBloxBluetooth.cpp'
];

const sources = {};

for (const name of runtimeFileNames) {
    sources[name] =
        fs.readFileSync(
            path.join(
                sourceDirectory,
                name
            ),
            'utf8'
        ).replace(
            /\r\n/g,
            '\n'
        );
}

const output = [
    '/* eslint-disable */',
    '// Generated by scripts/generate-easyblox-arduino-runtime.js.',
    '// Do not edit this file directly.',
    '',
    `const EASYBLOX_ARDUINO_RUNTIME_SOURCES = Object.freeze(${
        JSON.stringify(
            sources,
            null,
            4
        )
    });`,
    '',
    'module.exports = {',
    '    EASYBLOX_ARDUINO_RUNTIME_SOURCES',
    '};',
    ''
].join('\n');

fs.mkdirSync(
    outputDirectory,
    {
        recursive: true
    }
);

fs.writeFileSync(
    outputPath,
    output,
    'utf8'
);
