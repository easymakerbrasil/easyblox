const fs = require('fs');
const path = require('path');

const scriptDirectory =
    path.dirname(
        require.main.filename
    );

const outputDirectory =
    path.resolve(
        scriptDirectory,
        '../src/upload/generated'
    );

const generateSourcesModule = ({
    sourceDirectory,
    fileNames,
    outputFileName,
    constantName
}) => {
    const sources = {};

    for (const name of fileNames) {
        sources[name] =
            fs.readFileSync(
                path.join(
                    sourceDirectory,
                    name
                ),
                'utf8'
            ).replace(
                /\r\n/g,
                '\n'
            );
    }

    const output = [
        '/* eslint-disable */',
        '// Generated by scripts/generate-easyblox-arduino-runtime.js.',
        '// Do not edit this file directly.',
        '',
        `const ${constantName} = Object.freeze(${
            JSON.stringify(
                sources,
                null,
                4
            )
        });`,
        '',
        'module.exports = {',
        `    ${constantName}`,
        '};',
        ''
    ].join('\n');

    fs.mkdirSync(
        outputDirectory,
        {
            recursive: true
        }
    );

    fs.writeFileSync(
        path.join(
            outputDirectory,
            outputFileName
        ),
        output,
        'utf8'
    );
};

generateSourcesModule({
    sourceDirectory:
        path.resolve(
            scriptDirectory,
            '../src/upload/arduino-runtime'
        ),
    fileNames: [
        'EasyBlox.h',
        'EasyBloxBluetooth.h',
        'EasyBloxBluetooth.cpp'
    ],
    outputFileName:
        'easyblox-arduino-runtime-files.js',
    constantName:
        'EASYBLOX_ARDUINO_RUNTIME_SOURCES'
});

